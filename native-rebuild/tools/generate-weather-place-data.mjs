// Build-time only: extract the original OpenCC 1.4.2 t->cn dictionaries.
// Runtime uses read-only packed tables, no JavaScript, trie heap or DLL.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const source = process.argv[2];
if (!source) throw new Error('Pass the original opencc-js package directory');
if (JSON.parse(fs.readFileSync(path.join(source, 'package.json'))).version !== '1.4.2')
  throw new Error('Expected original opencc-js 1.4.2');
const dictionaries = {};
for (const name of ['CJK_Compatibility_Ideographs', 'TSCharacters', 'TSPhrases']) {
  const filename = path.join(source, 'dist/esm-lib/dict', `${name}.js`);
  const data = (await import(pathToFileURL(filename))).default;
  dictionaries[name] = typeof data === 'string' ? data.split('|').map(line => line.split(' ').slice(0, 2)) : data;
  console.log(`${name}: ${dictionaries[name].length} entries; sha256=${createHash('sha256').update(fs.readFileSync(filename)).digest('hex')}`);
}
function table(name, entries) {
  const sorted = [...new Map(entries)].sort((a, b) => Buffer.compare(Buffer.from(a[0]), Buffer.from(b[0])));
  let offset = 0;
  const records = [], literals = [];
  for (const [key, value] of sorted) {
    const keyLength = Buffer.byteLength(key), valueLength = Buffer.byteLength(value);
    records.push(`{${offset},${offset + keyLength},${keyLength},${valueLength}}`);
    literals.push(`u8${JSON.stringify(key + value)}`);
    offset += keyLength + valueLength;
  }
  return `constexpr char ${name}Text[] =\n${literals.join('\n')};\n` +
    `constexpr PlaceEntry ${name}Entries[] = {\n${records.join(',\n')}\n};\n` +
    `constexpr std::size_t ${name}Max = ${Math.max(...sorted.map(([key]) => Buffer.byteLength(key)))};\n`;
}
const text = '// Generated by tools/generate-weather-place-data.mjs from opencc-js 1.4.2.\n' +
  '// Dictionary data: Apache-2.0; see licenses/opencc-data-SOURCES.md.\n' +
  table('Compatibility', dictionaries.CJK_Compatibility_Ideographs) +
  table('Simplified', [...dictionaries.TSCharacters, ...dictionaries.TSPhrases]);
const destination = path.join(root, 'core/weather/weather_places_data.inc');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== text) throw new Error('Generated tables differ');
} else fs.writeFileSync(destination, text);
const executableIndex = process.argv.indexOf('--verify-native');
if (executableIndex >= 0) {
  const { Converter } = await import(pathToFileURL(path.join(source, 'dist/esm/full.js')));
  const convert = Converter({ from: 't', to: 'cn' });
  const samples = new Set(['蘇州市', '臺北市', '重慶市', '廣東省', '昆山', '拉薩市',
    '市北區', '乾縣', '香港特別行政區', '阿壩藏族羌族自治州']);
  for (const entries of Object.values(dictionaries)) for (const [key] of entries) {
    samples.add(key);
    samples.add(`蘇${key}縣`);
  }
  const input = [...samples];
  const output = spawnSync(process.argv[executableIndex + 1], ['--simplify'], {
    input: input.map(JSON.stringify).join('\n') + '\n', encoding: 'utf8', maxBuffer: 8 * 1024 * 1024
  });
  if (output.status !== 0) throw new Error(`Native comparison failed: ${output.stderr}`);
  const actual = output.stdout.trim().split(/\r?\n/).map(JSON.parse);
  if (actual.length !== input.length) throw new Error('Native output length differs');
  input.forEach((name, i) => {
    const expected = convert(name);
    if (actual[i] !== expected) throw new Error(`Mismatch: ${name}: ${actual[i]} != ${expected}`);
  });
  console.log(`Original Converter({from:t,to:cn}), applied unconditionally for Simplified Chinese: ${input.length} comparisons, zero differences`);
}
