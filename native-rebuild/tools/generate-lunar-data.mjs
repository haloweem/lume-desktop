function array(name, type, values, width = 16) {
  const lines = [];
  for (let i = 0; i < values.length; i += width) lines.push(`    ${values.slice(i, i + width).join(', ')},`);
  return `constexpr ${type} ${name}[] = {\n${lines.join('\n')}\n};\n`;
}
