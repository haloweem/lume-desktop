function dictionary(initial = []) {
  const values = [], ids = new Map();
  const add = value => {
    const key = JSON.stringify(value);
    if (!ids.has(key)) {
      assert(values.length < 65536, 'Generated uint16_t dictionary overflow');
      ids.set(key, values.length);
      values.push(value);
    }
    return ids.get(key);
  };
  for (const value of initial) add(value);
  return {values, add};
}
