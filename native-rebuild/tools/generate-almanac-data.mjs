// Development only: no JS engine or full-table decoding in the installed app.
// node tools/generate-almanac-data.mjs <read-only original widgets directory>
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
assert(process.argv.length===3,'Pass the original widgets directory');
const source=path.resolve(process.argv[2]);
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sha256=data=>crypto.createHash('sha256').update(data).digest('hex');
const sourceFiles=[
  ['lunar-calendar.js','a20464beb83aebce31003f22ec6c0961e687836381c4d0b57d87b42c5da7dfec'],
  ['vendor/lunar.js','5e6f2c23c669235cdad68681cbb39775b5565e99854a215f843a8cd53db996f1'],
].map(([file,expected])=>{
  const bytes=fs.readFileSync(path.join(source,file));
  assert.equal(sha256(bytes),expected,`${file} differs from the reviewed source`);
  return {file,sha256:expected};
});
const {Solar}=createRequire(import.meta.url)(path.join(source,'vendor/lunar.js'));
function dictionary(limit){
  const values=[],indices=new Map();
  return {values,add(value){
    const key=JSON.stringify(value);
    if(!indices.has(key)){
      assert(values.length<limit,'dictionary overflow');
      indices.set(key,values.length);values.push(value);
    }
    return indices.get(key);
  }};
}
const strings=dictionary(65536),years=dictionary(256),cycles=dictionary(256),lists=dictionary(65536);
const dayCycles=[],dayLists=[];
for(let time=Date.UTC(1900,0,1);time<Date.UTC(2101,0,1);time+=86400000){
  const date=new Date(time),solar=Solar.fromYmd(date.getUTCFullYear(),date.getUTCMonth()+1,date.getUTCDate()),lunar=solar.getLunar();
  dayCycles.push(years.add(`${lunar.getYearInGanZhi()}年(${lunar.getYearShengXiao()})`),
    cycles.add(lunar.getMonthInGanZhi()),cycles.add(lunar.getDayInGanZhi()));
  for(const values of [lunar.getDayYi(),lunar.getDayJi()]){
    assert(values.every(value=>typeof value==='string'&&!value.includes('\0')),'valid activities');
    dayLists.push(lists.add(values.map(value=>strings.add(value))));
  }
  if(date.getUTCMonth()===11&&date.getUTCDate()===31&&date.getUTCFullYear()%20===0)
    console.log(`Almanac through ${date.getUTCFullYear()}`);
}
const yearIds=years.values.map(value=>strings.add(value)),cycleIds=cycles.values.map(value=>strings.add(value));
const items=[],spans=[];
for(const list of lists.values){spans.push([items.length,list.length]);items.push(...list);}
const buffers=strings.values.map(value=>Buffer.from(`${value}\0`,'utf8')),offsets=[];
let size=0;for(const value of buffers){offsets.push(size);size+=value.length;}
function array(name,type,values,width=20){
  const lines=[];for(let i=0;i<values.length;i+=width)lines.push(`    ${values.slice(i,i+width).join(',')},`);
  return `constexpr ${type} ${name}[] = {\n${lines.join('\n')}\n};\n`;
}
const escape=bytes=>Array.from(bytes,value=>`\\${value.toString(8).padStart(3,'0')}`).join('');
const text=[
  '// Generated by tools/generate-almanac-data.mjs. Do not edit.\n'+
  '// lunar-javascript 1.7.7 (MIT), Copyright (c) 2018 6tail.\n'+
  '// See almanac_data.sources.json and ../../licenses/lunar-javascript-LICENSE.txt.\n',
  `constexpr char kStrings[] =\n${buffers.map(bytes=>`    "${escape(bytes)}"`).join('\n')};`,
  array('kOffsets','std::uint32_t',offsets),
  array('kYears','std::uint16_t',yearIds),array('kCycles','std::uint16_t',cycleIds),
  array('kItems','std::uint16_t',items),
  'struct ListSpan { std::uint32_t offset,count; };',
  array('kLists','ListSpan',spans.map(values=>`{${values.join(',')}}`),6),
  array('kDayCycles','std::uint8_t',dayCycles),
  array('kDayLists','std::uint16_t',dayLists),
  'static_assert(sizeof(kDayCycles)==73414*3);\nstatic_assert(sizeof(kDayLists)==73414*4);\n',
].join('\n');
const compiledArrayBytes=size+1+offsets.length*4+(yearIds.length+cycleIds.length+items.length+dayLists.length)*2+
  spans.length*8+dayCycles.length;
assert(compiledArrayBytes<1024*1024,'almanac immutable data exceeds 1 MiB budget');
const output=path.join(root,'core/almanac');
fs.mkdirSync(output,{recursive:true});
fs.writeFileSync(path.join(output,'almanac_data.inc'),text);
const manifest={sourceProject:'lunar-javascript',sourceVersion:'1.7.7',license:'MIT',sourceFiles,
  range:{first:'1900-01-01',last:'2100-12-31',days:73414},compiledArrayBytes,
  generatedSourceSha256:sha256(text),generatedSourceBytes:Buffer.byteLength(text),
  counts:{activities:strings.values.length,years:yearIds.length,cycles:cycleIds.length,lists:spans.length},
  policy:'Exact daily original algorithm outputs; lunar date reuses calendar data. No predictions or substitute yi/ji.'};
fs.writeFileSync(path.join(output,'almanac_data.sources.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify(manifest));
