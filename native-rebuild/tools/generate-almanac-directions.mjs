// Development only. node tools/generate-almanac-directions.mjs <lunar-1.7.7.cjs>
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const input=process.argv[2];
assert(input&&process.argv.length===3,'Pass the pinned lunar-javascript source');
const source=path.resolve(input),sha256=bytes=>createHash('sha256').update(bytes).digest('hex');
const expected='9750324bfe1aa63c146f8c72b1143df924466c11c8a5277d7d9225c541a18aaa';
assert.equal(sha256(fs.readFileSync(source)),expected,'Expected upstream v1.7.7 source');
const {Solar}=createRequire(import.meta.url)(source);
const rows=[];
for(let day=7;day<=16;++day){
  const lunar=Solar.fromYmd(2026,10,day).getLunar();
  rows.push([lunar.getDayGan(),lunar.getDayPositionCaiDesc(),lunar.getDayPositionXiDesc(),
    lunar.getDayPositionFuDesc(2),lunar.getDayPositionYangGuiDesc()]);
}
assert.equal(new Set(rows.map(row=>row[0])).size,10);
const text='// Generated by tools/generate-almanac-directions.mjs; do not edit.\n'+
  '// lunar-javascript 1.7.7 (MIT), Copyright (c) 2018 6tail.\n'+
  '// See almanac_directions.sources.json and ../../licenses/lunar-javascript-LICENSE.txt.\n'+
  'struct DirectionRow { std::string_view stem; Directions positions; };\n'+
  'constexpr DirectionRow kDirections[] = {\n'+rows.map(([stem,...values])=>
    `    {u8"${stem}",{${values.map(value=>`u8"${value}"`).join(',')}}},`).join('\n')+'\n};\n';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../core/almanac');
fs.writeFileSync(path.join(root,'almanac_directions.inc'),text);
fs.writeFileSync(path.join(root,'almanac_directions.sources.json'),JSON.stringify({
  sourceProject:'lunar-javascript',sourceVersion:'1.7.7',license:'MIT',
  upstream:'https://raw.githubusercontent.com/6tail/lunar-javascript/v1.7.7/lunar.js',sourceSha256:expected,
  methods:['getDayPositionCaiDesc','getDayPositionXiDesc','getDayPositionFuDesc(2)','getDayPositionYangGuiDesc'],
  policy:'Ten day-stem lookup rows; dates and activities continue to use the existing offline almanac data.',
  generatedSourceSha256:sha256(text),rows:10,
},null,2)+'\n');
console.log('Generated 10 original day-stem direction rows.');
