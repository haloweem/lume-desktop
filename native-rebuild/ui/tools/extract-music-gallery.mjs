// Build-time only: read the historical checkout, emit browser-only Gallery dependencies.
import {createRequire} from 'node:module';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';
import path from 'node:path';

if (!process.argv[2]) throw new Error('Usage: node extract-music-gallery.mjs <read-only upstream>');
const reference=path.resolve(process.argv[2]);
const require=createRequire(path.join(reference,'package.json'));
const {rolldown}=await import(pathToFileURL(require.resolve('rolldown')).href);
const output=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../music-visualizers/gallery-vendor');
const check=process.argv.includes('--check');
if(!check)mkdirSync(output,{recursive:true});
function emit(name,content) {
  const destination=path.join(output,name),bytes=Buffer.from(content);
  if(check) {
    if(!readFileSync(destination).equals(bytes))throw new Error(`Non-reproducible Gallery artifact: ${name}`);
  } else writeFileSync(destination,bytes);
}
const hashes=new Map();
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const relative=file=>path.relative(reference,file).replaceAll('\\','/');
const track=file=>{hashes.set(relative(file),hash(readFileSync(file)));};
const monet='src/components/visualizer/monet/monetLyricsModel.ts';
const coreEntry=`export {buildMonetVisibleLineEntries, buildMonetDisplayTokens, measureMonetLineLayout, measureMonetGraphemeOffsets, resolveMonetCollisionHeight, resolveMonetSweepEdgeSoftness, resolveMonetSweepEnd, clearGalleryMeasurements} from './${monet}';
export {getLineRenderEndTime} from './src/utils/lyrics/renderHints.ts';`;
const motionEntry=`export {spring} from './node_modules/motion-dom/dist/es/animation/generators/spring.mjs';
export {cubicBezier} from './node_modules/motion-utils/dist/es/easing/cubic-bezier.mjs';`;

async function bundle(entry,name,format) {
  const build=await rolldown({cwd:reference,input:'\0gallery-entry',platform:'browser',
    transform:{define:{'process.env.NODE_ENV':'"production"'}},
    plugins:[{name:'gallery-read-only-source',
      resolveId(source,importer){
        if(source==='\0gallery-entry')return source;
        if(importer==='\0gallery-entry')return path.resolve(reference,source);
      },
      load(id){
        if(id==='\0gallery-entry')return entry;
        if(!id.startsWith('\0'))track(id);
      },
      transform(code,id){
        if(relative(id)===monet) {
          // Keyword coloring is disabled by the real Gallery entry; exclude its unused re-exports.
          code=code.replace(/export \{[\s\S]*?\} from '\.\.\/wordColoring';/, '');
          code=`import {clearCache as clearPretextCache} from '@chenglou/pretext';\n${code}\nexport function clearGalleryMeasurements(){monetGraphemeOffsetsCache.clear();monetVerticalMetricsCache.clear();monetVerticalMeasureContext=null;clearPretextCache();}\n`;
        }
        if(relative(id)==='node_modules/@chenglou/pretext/dist/measurement.js') {
          code=code.replace('export function clearMeasurementCaches() {','export function clearMeasurementCaches() {\n    measureContext = null;\n    cachedEngineProfile = null;');
        }
        return code;
      },
    }],
  });
  const {output:chunks}=await build.generate({format,name:format==='iife'?'GalleryCore':undefined,
    minify:false,comments:{legal:true},sourcemap:false});
  await build.close();
  if(chunks.length!==1 || chunks[0].type!=='chunk')throw new Error('Expected one self-contained chunk');
  const code=chunks[0].code;
  if(/\b(?:require\(|React\.|react-dom|node:)/.test(code))throw new Error('Non-browser dependency leaked');
  const header='// Generated by tools/extract-music-gallery.mjs. See gallery-SOURCES.md and manifest.json.\n';
  const result=format==='iife'
    ? `${header}export function createGalleryCore(document = globalThis.document) {\n${code}\nreturn GalleryCore;\n}\n`
    : header+code;
  emit(name,result);
  return {path:name,sha256:hash(result),bytes:Buffer.byteLength(result)};
}
const generated=[];
generated.push(await bundle(coreEntry,'monet-core.js','iife'));
generated.push(await bundle(motionEntry,'motion.js','es'));
const sources=[
  'src/components/visualizer/gallery/VisualizerGallery.tsx',
  'src/components/visualizer/gallery/galleryLyricsModel.ts',
  'src/components/visualizer/monet/MonetLyricsRail.tsx',
  'src/components/visualizer/runtime.ts',
  'src/utils/fontStacks.ts',
  'src/stores/useSettingsUiStore.ts',
  'src/components/app/presentation/buildVisualizerTheme.ts',
  'src/components/visualizer/backgrounds/wallpaper/WallpaperMedia.tsx',
  'src/services/lumenicBackgroundMedia.ts',
  'node_modules/rolldown/package.json',
  'node_modules/motion-dom/package.json',
  'node_modules/motion-utils/package.json',
  'node_modules/@chenglou/pretext/package.json',
];
for(const source of sources)track(path.join(reference,source));
for(const [source,destination] of [
  ['LICENSE','Folia-AGPL-3.0.txt'],
  ['node_modules/@chenglou/pretext/LICENSE','pretext-LICENSE.txt'],
  ['node_modules/motion-dom/LICENSE.md','motion-dom-LICENSE.txt'],
  ['node_modules/motion-utils/LICENSE.md','motion-utils-LICENSE.txt'],
]) {
  track(path.join(reference,source));
  emit(destination,readFileSync(path.join(reference,source)));
}
const manifest={schema:1,reference:'lume1.0.1/third_party/folia-major/upstream',
  versions:Object.fromEntries(['rolldown','motion-dom','motion-utils','@chenglou/pretext'].map(name=>[name,JSON.parse(readFileSync(path.join(reference,'node_modules',name,'package.json'),'utf8')).version])),
  adaptations:['Only Monet pure model exports; no GalleryLyricsRail or React runtime.',
    'Factory scopes all Pretext/Monet caches per mount; explicit cache/context cleanup added.',
    'Motion native spring and cubicBezier generators only; caller owns scheduling.'],
  sources:Object.fromEntries([...hashes].sort(([a],[b])=>a.localeCompare(b,'en'))),generated};
emit('manifest.json',JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify({check,generated,sourceCount:hashes.size,versions:manifest.versions},null,2));
